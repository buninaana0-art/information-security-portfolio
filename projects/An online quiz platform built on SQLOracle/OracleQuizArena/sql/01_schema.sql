

CREATE TABLE qp_users (
    user_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    oracle_username     VARCHAR2(128) NOT NULL,
    display_name        VARCHAR2(100) NOT NULL,
    email               VARCHAR2(255) NOT NULL,
    password_salt       VARCHAR2(32) NOT NULL,
    password_hash       VARCHAR2(64) NOT NULL,
    avatar_url          VARCHAR2(1000),
    user_role           VARCHAR2(20) DEFAULT 'PARTICIPANT' NOT NULL,
    user_status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    registered_at       TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT qp_users_pk PRIMARY KEY (user_id),
    CONSTRAINT qp_users_role_ck CHECK (user_role IN ('PARTICIPANT', 'AUTHOR', 'ADMIN')),
    CONSTRAINT qp_users_status_ck CHECK (user_status IN ('ACTIVE', 'BLOCKED'))
);

CREATE UNIQUE INDEX qp_users_email_uq ON qp_users (LOWER(email));
CREATE UNIQUE INDEX qp_users_ora_uq ON qp_users (UPPER(oracle_username));

CREATE TABLE qp_sessions (
    session_token       VARCHAR2(64),
    user_id             NUMBER NOT NULL,
    created_at          TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    last_seen_at        TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    expires_at          TIMESTAMP NOT NULL,
    revoked_flag        CHAR(1) DEFAULT 'N' NOT NULL,
    client_label        VARCHAR2(255),
    CONSTRAINT qp_sessions_pk PRIMARY KEY (session_token),
    CONSTRAINT qp_sessions_user_fk FOREIGN KEY (user_id)
        REFERENCES qp_users (user_id) ON DELETE CASCADE,
    CONSTRAINT qp_sessions_rev_ck CHECK (revoked_flag IN ('Y', 'N'))
);

CREATE INDEX qp_sessions_user_ix ON qp_sessions (user_id, revoked_flag, expires_at);

CREATE TABLE qp_categories (
    category_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    category_name       VARCHAR2(100) NOT NULL,
    description         VARCHAR2(1000),
    CONSTRAINT qp_categories_pk PRIMARY KEY (category_id),
    CONSTRAINT qp_categories_uq UNIQUE (category_name)
);

CREATE TABLE qp_topics (
    topic_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    owner_user_id        NUMBER NOT NULL,
    topic_name           VARCHAR2(100) NOT NULL,
    description          VARCHAR2(1000),
    created_at           TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT qp_topics_pk PRIMARY KEY (topic_id),
    CONSTRAINT qp_topics_owner_fk FOREIGN KEY (owner_user_id)
        REFERENCES qp_users (user_id) ON DELETE CASCADE,
    CONSTRAINT qp_topics_uq UNIQUE (owner_user_id, topic_name)
);

CREATE TABLE qp_question_types (
    question_type_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    type_code            VARCHAR2(30) NOT NULL,
    type_name            VARCHAR2(100) NOT NULL,
    description          VARCHAR2(1000),
    CONSTRAINT qp_qtypes_pk PRIMARY KEY (question_type_id),
    CONSTRAINT qp_qtypes_code_uq UNIQUE (type_code),
    CONSTRAINT qp_qtypes_name_uq UNIQUE (type_name),
    CONSTRAINT qp_qtypes_code_ck CHECK (
        type_code IN ('SINGLE', 'MULTIPLE', 'TEXT', 'TRUE_FALSE',
                      'NUMBER', 'ORDERING', 'MATCHING')
    )
);

CREATE TABLE qp_tests (
    test_id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    author_user_id           NUMBER NOT NULL,
    primary_category_id      NUMBER NOT NULL,
    test_title               VARCHAR2(255) NOT NULL,
    description              VARCHAR2(2000),
    test_status              VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    access_mode              VARCHAR2(20) DEFAULT 'PUBLIC' NOT NULL,
    time_limit_minutes       NUMBER(6),
    question_count           NUMBER(6),
    pass_percent             NUMBER(5,2) DEFAULT 60 NOT NULL,
    feedback_mode            VARCHAR2(20) DEFAULT 'AFTER_TEST' NOT NULL,
    show_correct_answers     CHAR(1) DEFAULT 'Y' NOT NULL,
    adaptive_flag            CHAR(1) DEFAULT 'N' NOT NULL,
    team_mode_flag           CHAR(1) DEFAULT 'N' NOT NULL,
    max_attempts             NUMBER(6),
    created_at               TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    published_at             TIMESTAMP,
    CONSTRAINT qp_tests_pk PRIMARY KEY (test_id),
    CONSTRAINT qp_tests_author_fk FOREIGN KEY (author_user_id)
        REFERENCES qp_users (user_id),
    CONSTRAINT qp_tests_cat_fk FOREIGN KEY (primary_category_id)
        REFERENCES qp_categories (category_id),
    CONSTRAINT qp_tests_status_ck CHECK (test_status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT qp_tests_access_ck CHECK (access_mode IN ('PUBLIC', 'RESTRICTED')),
    CONSTRAINT qp_tests_feedback_ck CHECK (feedback_mode IN ('IMMEDIATE', 'AFTER_TEST', 'NEVER')),
    CONSTRAINT qp_tests_correct_ck CHECK (show_correct_answers IN ('Y', 'N')),
    CONSTRAINT qp_tests_adapt_ck CHECK (adaptive_flag IN ('Y', 'N')),
    CONSTRAINT qp_tests_team_ck CHECK (team_mode_flag IN ('Y', 'N')),
    CONSTRAINT qp_tests_time_ck CHECK (time_limit_minutes IS NULL OR time_limit_minutes > 0),
    CONSTRAINT qp_tests_count_ck CHECK (question_count IS NULL OR question_count > 0),
    CONSTRAINT qp_tests_pass_ck CHECK (pass_percent BETWEEN 0 AND 100),
    CONSTRAINT qp_tests_attempts_ck CHECK (max_attempts IS NULL OR max_attempts > 0)
);

CREATE INDEX qp_tests_author_ix ON qp_tests (author_user_id, test_status);
CREATE INDEX qp_tests_cat_ix ON qp_tests (primary_category_id, test_status);

CREATE TABLE qp_test_topics (
    test_id              NUMBER NOT NULL,
    topic_id             NUMBER NOT NULL,
    CONSTRAINT qp_test_topics_pk PRIMARY KEY (test_id, topic_id),
    CONSTRAINT qp_tt_test_fk FOREIGN KEY (test_id)
        REFERENCES qp_tests (test_id) ON DELETE CASCADE,
    CONSTRAINT qp_tt_topic_fk FOREIGN KEY (topic_id)
        REFERENCES qp_topics (topic_id) ON DELETE CASCADE
);

CREATE TABLE qp_test_access (
    test_id              NUMBER NOT NULL,
    oracle_username      VARCHAR2(128) NOT NULL,
    granted_by_user_id   NUMBER NOT NULL,
    granted_at           TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT qp_test_access_pk PRIMARY KEY (test_id, oracle_username),
    CONSTRAINT qp_ta_test_fk FOREIGN KEY (test_id)
        REFERENCES qp_tests (test_id) ON DELETE CASCADE,
    CONSTRAINT qp_ta_grantor_fk FOREIGN KEY (granted_by_user_id)
        REFERENCES qp_users (user_id)
);

CREATE INDEX qp_test_access_ora_ix ON qp_test_access (UPPER(oracle_username));

CREATE TABLE qp_questions (
    question_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    test_id              NUMBER NOT NULL,
    question_type_id     NUMBER NOT NULL,
    category_id          NUMBER NOT NULL,
    question_text        CLOB NOT NULL,
    difficulty_level     NUMBER(1) DEFAULT 3 NOT NULL,
    display_order        NUMBER(6) NOT NULL,
    points               NUMBER(8,2) DEFAULT 1 NOT NULL,
    time_limit_seconds   NUMBER(8),
    adaptive_flag        CHAR(1) DEFAULT 'Y' NOT NULL,
    explanation          CLOB,
    image_data           BLOB,
    image_mime_type      VARCHAR2(100),
    image_file_name      VARCHAR2(255),
    active_flag          CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at           TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT qp_questions_pk PRIMARY KEY (question_id),
    CONSTRAINT qp_questions_test_fk FOREIGN KEY (test_id)
        REFERENCES qp_tests (test_id) ON DELETE CASCADE,
    CONSTRAINT qp_questions_type_fk FOREIGN KEY (question_type_id)
        REFERENCES qp_question_types (question_type_id),
    CONSTRAINT qp_questions_cat_fk FOREIGN KEY (category_id)
        REFERENCES qp_categories (category_id),
    CONSTRAINT qp_questions_order_uq UNIQUE (test_id, display_order),
    CONSTRAINT qp_questions_diff_ck CHECK (difficulty_level BETWEEN 1 AND 5),
    CONSTRAINT qp_questions_points_ck CHECK (points > 0),
    CONSTRAINT qp_questions_time_ck CHECK (time_limit_seconds IS NULL OR time_limit_seconds > 0),
    CONSTRAINT qp_questions_adapt_ck CHECK (adaptive_flag IN ('Y', 'N')),
    CONSTRAINT qp_questions_active_ck CHECK (active_flag IN ('Y', 'N')),
    CONSTRAINT qp_questions_img_ck CHECK (
        (image_mime_type IS NULL AND image_file_name IS NULL)
        OR
        (image_mime_type IS NOT NULL AND image_file_name IS NOT NULL)
    )
);

CREATE INDEX qp_questions_pick_ix ON qp_questions
    (test_id, active_flag, category_id, difficulty_level, adaptive_flag);

CREATE TABLE qp_answer_options (
    option_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    question_id          NUMBER NOT NULL,
    option_text          VARCHAR2(1000) NOT NULL,
    is_correct           CHAR(1) DEFAULT 'N' NOT NULL,
    display_order        NUMBER(6) NOT NULL,
    correct_order        NUMBER(6),
    match_key            VARCHAR2(500),
    image_data           BLOB,
    image_mime_type      VARCHAR2(100),
    image_file_name      VARCHAR2(255),
    CONSTRAINT qp_options_pk PRIMARY KEY (option_id),
    CONSTRAINT qp_options_question_fk FOREIGN KEY (question_id)
        REFERENCES qp_questions (question_id) ON DELETE CASCADE,
    CONSTRAINT qp_options_order_uq UNIQUE (question_id, display_order),
    CONSTRAINT qp_options_correct_ck CHECK (is_correct IN ('Y', 'N')),
    CONSTRAINT qp_options_img_ck CHECK (
        (image_mime_type IS NULL AND image_file_name IS NULL)
        OR
        (image_mime_type IS NOT NULL AND image_file_name IS NOT NULL)
    )
);

CREATE INDEX qp_options_question_ix ON qp_answer_options (question_id, is_correct);

CREATE UNIQUE INDEX qp_options_corr_uq ON qp_answer_options (
    CASE WHEN correct_order IS NOT NULL THEN question_id END,
    CASE WHEN correct_order IS NOT NULL THEN correct_order END
);

CREATE TABLE qp_question_keys (
    key_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    question_id          NUMBER NOT NULL,
    key_type             VARCHAR2(20) NOT NULL,
    accepted_text        VARCHAR2(1000),
    numeric_value        NUMBER,
    numeric_tolerance    NUMBER DEFAULT 0,
    case_sensitive_flag  CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT qp_qkeys_pk PRIMARY KEY (key_id),
    CONSTRAINT qp_qkeys_question_fk FOREIGN KEY (question_id)
        REFERENCES qp_questions (question_id) ON DELETE CASCADE,
    CONSTRAINT qp_qkeys_type_ck CHECK (key_type IN ('TEXT', 'REGEX', 'NUMBER')),
    CONSTRAINT qp_qkeys_case_ck CHECK (case_sensitive_flag IN ('Y', 'N')),
    CONSTRAINT qp_qkeys_value_ck CHECK (
        (key_type IN ('TEXT', 'REGEX') AND accepted_text IS NOT NULL AND numeric_value IS NULL)
        OR
        (key_type = 'NUMBER' AND accepted_text IS NULL AND numeric_value IS NOT NULL)
    ),
    CONSTRAINT qp_qkeys_tol_ck CHECK (numeric_tolerance IS NULL OR numeric_tolerance >= 0)
);

CREATE TABLE qp_test_rules (
    rule_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    test_id               NUMBER NOT NULL,
    category_id           NUMBER,
    difficulty_level      NUMBER(1),
    question_count        NUMBER(6) NOT NULL,
    CONSTRAINT qp_rules_pk PRIMARY KEY (rule_id),
    CONSTRAINT qp_rules_test_fk FOREIGN KEY (test_id)
        REFERENCES qp_tests (test_id) ON DELETE CASCADE,
    CONSTRAINT qp_rules_cat_fk FOREIGN KEY (category_id)
        REFERENCES qp_categories (category_id),
    CONSTRAINT qp_rules_diff_ck CHECK (difficulty_level IS NULL OR difficulty_level BETWEEN 1 AND 5),
    CONSTRAINT qp_rules_count_ck CHECK (question_count > 0)
);

CREATE INDEX qp_rules_test_ix ON qp_test_rules (test_id);

CREATE TABLE qp_teams (
    team_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    owner_user_id         NUMBER NOT NULL,
    team_name             VARCHAR2(100) NOT NULL,
    join_code             VARCHAR2(20) NOT NULL,
    created_at            TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    active_flag           CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT qp_teams_pk PRIMARY KEY (team_id),
    CONSTRAINT qp_teams_owner_fk FOREIGN KEY (owner_user_id)
        REFERENCES qp_users (user_id),
    CONSTRAINT qp_teams_name_uq UNIQUE (team_name),
    CONSTRAINT qp_teams_code_uq UNIQUE (join_code),
    CONSTRAINT qp_teams_active_ck CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE qp_team_members (
    team_id               NUMBER NOT NULL,
    user_id               NUMBER NOT NULL,
    member_role           VARCHAR2(20) DEFAULT 'MEMBER' NOT NULL,
    joined_at             TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT qp_team_members_pk PRIMARY KEY (team_id, user_id),
    CONSTRAINT qp_tm_team_fk FOREIGN KEY (team_id)
        REFERENCES qp_teams (team_id) ON DELETE CASCADE,
    CONSTRAINT qp_tm_user_fk FOREIGN KEY (user_id)
        REFERENCES qp_users (user_id) ON DELETE CASCADE,
    CONSTRAINT qp_tm_role_ck CHECK (member_role IN ('CAPTAIN', 'MEMBER'))
