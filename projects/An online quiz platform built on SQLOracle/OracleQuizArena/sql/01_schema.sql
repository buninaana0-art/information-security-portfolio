CREATE TABLE qp_attempts (
    attempt_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    user_id                NUMBER NOT NULL,
    test_id                NUMBER NOT NULL,
    team_id                NUMBER,
    attempt_status         VARCHAR2(20) DEFAULT 'IN_PROGRESS' NOT NULL,
    started_at             TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    deadline_at            TIMESTAMP,
    finished_at            TIMESTAMP,
    score                  NUMBER(10,2) DEFAULT 0 NOT NULL,
    max_score              NUMBER(10,2) DEFAULT 0 NOT NULL,
    percent_score          NUMBER(5,2) DEFAULT 0 NOT NULL,
    correct_count          NUMBER(6) DEFAULT 0 NOT NULL,
    target_question_count  NUMBER(6) NOT NULL,
    current_difficulty     NUMBER(1) DEFAULT 3 NOT NULL,
    finish_reason          VARCHAR2(30),
    CONSTRAINT qp_attempts_pk PRIMARY KEY (attempt_id),
    CONSTRAINT qp_attempts_user_fk FOREIGN KEY (user_id)
        REFERENCES qp_users (user_id),
    CONSTRAINT qp_attempts_test_fk FOREIGN KEY (test_id)
        REFERENCES qp_tests (test_id),
    CONSTRAINT qp_attempts_team_fk FOREIGN KEY (team_id)
        REFERENCES qp_teams (team_id),
    CONSTRAINT qp_attempts_status_ck CHECK (
        attempt_status IN ('IN_PROGRESS', 'COMPLETED', 'TIMED_OUT', 'CANCELLED')
    ),
    CONSTRAINT qp_attempts_score_ck CHECK (score >= 0 AND max_score >= 0),
    CONSTRAINT qp_attempts_percent_ck CHECK (percent_score BETWEEN 0 AND 100),
    CONSTRAINT qp_attempts_target_ck CHECK (target_question_count > 0),
    CONSTRAINT qp_attempts_diff_ck CHECK (current_difficulty BETWEEN 1 AND 5)
);

CREATE INDEX qp_attempts_user_ix ON qp_attempts (user_id, started_at DESC);
CREATE INDEX qp_attempts_test_ix ON qp_attempts (test_id, attempt_status, started_at);
CREATE INDEX qp_attempts_team_ix ON qp_attempts (team_id, attempt_status);

CREATE TABLE qp_attempt_questions (
    attempt_question_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    attempt_id            NUMBER NOT NULL,
    question_id           NUMBER NOT NULL,
    sequence_no           NUMBER(6) NOT NULL,
    question_status       VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    assigned_at           TIMESTAMP,
    deadline_at           TIMESTAMP,
    answered_at           TIMESTAMP,
    is_correct            CHAR(1),
    points_awarded        NUMBER(8,2) DEFAULT 0 NOT NULL,
    CONSTRAINT qp_aq_pk PRIMARY KEY (attempt_question_id),
    CONSTRAINT qp_aq_attempt_fk FOREIGN KEY (attempt_id)
        REFERENCES qp_attempts (attempt_id) ON DELETE CASCADE,
    CONSTRAINT qp_aq_question_fk FOREIGN KEY (question_id)
        REFERENCES qp_questions (question_id),
    CONSTRAINT qp_aq_question_uq UNIQUE (attempt_id, question_id),
    CONSTRAINT qp_aq_sequence_uq UNIQUE (attempt_id, sequence_no),
    CONSTRAINT qp_aq_status_ck CHECK (
        question_status IN ('PENDING', 'ACTIVE', 'ANSWERED', 'TIMED_OUT')
    ),
    CONSTRAINT qp_aq_correct_ck CHECK (is_correct IS NULL OR is_correct IN ('Y', 'N')),
    CONSTRAINT qp_aq_points_ck CHECK (points_awarded >= 0)
);

CREATE INDEX qp_aq_next_ix ON qp_attempt_questions (attempt_id, question_status, sequence_no);

CREATE TABLE qp_attempt_options (
