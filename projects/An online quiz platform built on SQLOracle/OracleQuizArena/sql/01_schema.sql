CREATE TABLE qp_rating_snapshots (
    rating_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    rating_type           VARCHAR2(10) NOT NULL,
    user_id               NUMBER,
    team_id               NUMBER,
    period_code           VARCHAR2(10) NOT NULL,
    total_score           NUMBER(12,2) NOT NULL,
    completed_attempts    NUMBER(8) NOT NULL,
    rank_no               NUMBER(8) NOT NULL,
    calculated_at         TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT qp_ratings_pk PRIMARY KEY (rating_id),
    CONSTRAINT qp_ratings_user_fk FOREIGN KEY (user_id)
        REFERENCES qp_users (user_id) ON DELETE CASCADE,
    CONSTRAINT qp_ratings_team_fk FOREIGN KEY (team_id)
        REFERENCES qp_teams (team_id) ON DELETE CASCADE,
    CONSTRAINT qp_ratings_type_ck CHECK (rating_type IN ('USER', 'TEAM')),
    CONSTRAINT qp_ratings_period_ck CHECK (period_code IN ('WEEK', 'MONTH', 'ALL')),
    CONSTRAINT qp_ratings_subject_ck CHECK (
        (rating_type = 'USER' AND user_id IS NOT NULL AND team_id IS NULL)
        OR
        (rating_type = 'TEAM' AND user_id IS NULL AND team_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX qp_ratings_user_uq ON qp_rating_snapshots
    (CASE WHEN rating_type = 'USER' THEN user_id END,
     CASE WHEN rating_type = 'USER' THEN period_code END);
CREATE UNIQUE INDEX qp_ratings_team_uq ON qp_rating_snapshots
    (CASE WHEN rating_type = 'TEAM' THEN team_id END,
     CASE WHEN rating_type = 'TEAM' THEN period_code END);
CREATE INDEX qp_ratings_board_ix ON qp_rating_snapshots
    (rating_type, period_code, rank_no);

CREATE TABLE qp_certificates (
