    CONSTRAINT qp_cert_attempt_uq UNIQUE (attempt_id),
    CONSTRAINT qp_cert_no_uq UNIQUE (certificate_no),
    CONSTRAINT qp_cert_token_uq UNIQUE (verification_token)
);

CREATE TABLE qp_audit_log (
    audit_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000),
    event_time             TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    user_id                NUMBER,
    event_code             VARCHAR2(50) NOT NULL,
    entity_type            VARCHAR2(50),
    entity_id              NUMBER,
    details                VARCHAR2(2000),
    oracle_session_user    VARCHAR2(128) NOT NULL,
    CONSTRAINT qp_audit_pk PRIMARY KEY (audit_id),
    CONSTRAINT qp_audit_user_fk FOREIGN KEY (user_id)
        REFERENCES qp_users (user_id) ON DELETE SET NULL
);

CREATE INDEX qp_audit_event_ix ON qp_audit_log (event_time, event_code);

COMMENT ON TABLE qp_test_access IS
    'Access control list of Oracle database usernames for restricted tests.';
COMMENT ON TABLE qp_attempt_questions IS
    'Database-owned attempt plan and per-question timer state.';
COMMENT ON TABLE qp_certificates IS
    'PDF certificates generated entirely inside PL/SQL and stored as BLOB.';
